/**
 * NavGrid (v1.9 WP-O2, docs/OCEAN-PLAN.md): the walkability grid and A* the bots use on ELEVATED arenas (`arena.heightfield`).
 *
 * The Ocean Dome has three levels joined by ramps; everything else is a cliff a grounded fighter cannot climb (the sim's step rule,
 * `ARENA_STEP_UP` 0.6 m). A bot that seeks a target on another level in a straight line wedges against the cliff, so on such arenas
 * the brain asks this module for a path when the straight line is blocked by terrain. On flat arenas (colosseum, jungle) nothing here
 * is ever built or called, which keeps their behaviour byte-identical.
 *
 * Grid: {@link NAV_CELL} (0.75 m) cells over the dome. A cell is WALKABLE for a body of radius r (+ a per-level margin) iff
 * `arenaStandable` says so at its centre: inside the wall, clear of every cliff and of every solid. Edges join the 8 neighbours (a
 * diagonal also needs both orthogonal neighbours walkable) and cost their length plus a small penalty near cliffs/solids and beside
 * ledges, so a path keeps to the middle of a ramp (a 6 m ramp, a 1.2 m body, no cliff-corner clipping). DROP edges (walking off a ledge,
 * 0.45-1.9 m) are generated by marching from every ledge-top cell; they are optional (the search is given a drop cost, or forbids
 * them). The sim's jump (apex 1.2 m) cannot clear the Ocean's 1.5 m cliffs, but an up-step in (0.6, 1.0] m is generated as a JUMP edge
 * for arenas that have one (none today).
 *
 * Everything is pure and deterministic (no randomness, typed arrays, stable tie-breaks) and cached per (arena, radius, margin).
 */

import { ARENA_STEP_UP, arenaCliffDistance, arenaGroundHeight, arenaSolidDistance, type ArenaDef } from '../config/arenas';

export const NAV_CELL = 0.75;
/** A height LOSS larger than this between two samples is a ledge (ramp slopes are 0.25 rise/run: 0.19 m per 0.75 m cell). */
export const DROP_MIN = 0.45;
/** Tallest ledge a bot will deliberately walk off (the Ocean's levels are 1.5 m apart). */
export const DROP_MAX = 1.9;
/** Tallest up-step a bot will JUMP onto (apex of a jump is 1.225 m; leave margin). */
export const JUMP_MAX = 1.0;

/** Edge kinds (adjacency `kind`): 0 walk, 1 drop (off a ledge), 2 jump (up a 0.6-1.0 m step). */
export const EDGE_WALK = 0;
export const EDGE_DROP = 1;
export const EDGE_JUMP = 2;

export interface NavGrid {
  readonly arena: ArenaDef;
  /** Body radius and extra clearance this grid was built for. */
  readonly radius: number;
  readonly margin: number;
  /** Cells per side, world coordinate of the grid's lower-left corner, cell size. */
  readonly n: number;
  readonly origin: number;
  readonly cell: number;
  /** 1 where a body can stand (cliff + solid + wall clear). */
  readonly walk: Uint8Array;
  /** 1 where the cell is clear of solids and the wall (cliff clearance not required): the landing test for drops. */
  readonly solidOk: Uint8Array;
  /** 1 where a body of the bare radius (no margin) is clear of every cliff: the terrain-only test. */
  readonly cliffOk: Uint8Array;
  /** Ground height at each cell centre. */
  readonly h: Float32Array;
  /** CSR adjacency: edges of cell i are adjStart[i] .. adjStart[i+1]-1. */
  readonly adjStart: Int32Array;
  readonly adjTo: Int32Array;
  readonly adjCost: Float32Array;
  readonly adjKind: Uint8Array;
}

const CACHE = new WeakMap<ArenaDef, Map<string, NavGrid>>();

/** The (cached) grid for a body of `radius` plus `margin` on `arena`. Only meaningful for arenas with a heightfield. */
export function getNavGrid(arena: ArenaDef, radius: number, margin: number): NavGrid {
  let byKey = CACHE.get(arena);
  if (byKey === undefined) {
    byKey = new Map();
    CACHE.set(arena, byKey);
  }
  const key = `${radius.toFixed(2)}:${margin.toFixed(2)}`;
  let g = byKey.get(key);
  if (g === undefined) {
    g = buildGrid(arena, radius, margin);
    byKey.set(key, g);
  }
  return g;
}

const NB_DX = [1, -1, 0, 0, 1, 1, -1, -1];
const NB_DZ = [0, 0, 1, -1, 1, -1, 1, -1];

function buildGrid(arena: ArenaDef, radius: number, margin: number): NavGrid {
  const cell = NAV_CELL;
  const n = Math.ceil((arena.wallRadius * 2) / cell);
  const origin = -(n * cell) / 2;
  const N = n * n;
  const R = radius + margin;
  const walk = new Uint8Array(N);
  const solidOk = new Uint8Array(N);
  const cliffOk = new Uint8Array(N);
  const h = new Float32Array(N);
  const clr = new Float32Array(N);
  for (let iz = 0; iz < n; iz++) {
    for (let ix = 0; ix < n; ix++) {
      const i = iz * n + ix;
      const x = origin + (ix + 0.5) * cell;
      const z = origin + (iz + 0.5) * cell;
      h[i] = arenaGroundHeight(arena, x, z);
      const inside = Math.hypot(x, z) <= arena.wallRadius - R;
      const sd = arenaSolidDistance(arena, x, z);
      const cd = arenaCliffDistance(arena, x, z);
      solidOk[i] = inside && sd >= R ? 1 : 0;
      cliffOk[i] = Math.hypot(x, z) <= arena.wallRadius - radius && cd >= radius - 0.05 ? 1 : 0;
      walk[i] = inside && sd >= R && cd >= R ? 1 : 0;
      clr[i] = Math.min(cd, sd, 4);
    }
  }
  // Penalty for entering a cell near a cliff / solid, and beside a ledge (so paths use the middle of a ramp).
  const pen = new Float32Array(N);
  for (let iz = 0; iz < n; iz++) {
    for (let ix = 0; ix < n; ix++) {
      const i = iz * n + ix;
      if (walk[i] === 0) continue;
      let p = Math.min(1.2, Math.max(0, R + 1.2 - clr[i])) * 0.8;
      for (let d = 0; d < 8; d++) {
        const jx = ix + NB_DX[d];
        const jz = iz + NB_DZ[d];
        if (jx < 0 || jz < 0 || jx >= n || jz >= n) continue;
        if (h[i] - h[jz * n + jx] > DROP_MIN) {
          p += 1.0;
          break;
        }
      }
      pen[i] = p;
    }
  }

  // Edges: CSR over (walk edges, drop edges, jump edges).
  const toList: number[] = [];
  const costList: number[] = [];
  const kindList: number[] = [];
  const adjStart = new Int32Array(N + 1);
  for (let iz = 0; iz < n; iz++) {
    for (let ix = 0; ix < n; ix++) {
      const i = iz * n + ix;
      adjStart[i] = toList.length;
      if (walk[i] === 0) continue;
      const hasLedge = ledgeNear(h, n, ix, iz);
      for (let d = 0; d < 8; d++) {
        const jx = ix + NB_DX[d];
        const jz = iz + NB_DZ[d];
        if (jx < 0 || jz < 0 || jx >= n || jz >= n) continue;
        const j = jz * n + jx;
        if (walk[j] === 0) continue;
        if (d >= 4 && (walk[iz * n + jx] === 0 || walk[jz * n + ix] === 0)) continue; // no corner cutting
        const up = h[j] - h[i];
        const len = d < 4 ? cell : cell * Math.SQRT2;
        if (up > JUMP_MAX) continue;
        if (up > ARENA_STEP_UP) {
          toList.push(j);
          costList.push(len + 2.5 + pen[j]);
          kindList.push(EDGE_JUMP);
          continue;
        }
        if (-up > DROP_MIN) continue; // adjacent cells never differ this much on walkable ground; drops are generated below
        toList.push(j);
        costList.push(len + pen[j]);
        kindList.push(EDGE_WALK);
      }
      if (hasLedge) addDropEdges(arena, walk, solidOk, h, n, origin, cell, ix, iz, toList, costList, kindList);
    }
  }
  adjStart[N] = toList.length;
  return {
    arena,
    radius,
    margin,
    n,
    origin,
    cell,
    walk,
    solidOk,
    cliffOk,
    h,
    adjStart,
    adjTo: Int32Array.from(toList),
    adjCost: Float32Array.from(costList),
    adjKind: Uint8Array.from(kindList),
  };
}

function ledgeNear(h: Float32Array, n: number, ix: number, iz: number): boolean {
  const i = iz * n + ix;
  for (let d = 0; d < 8; d++) {
    const jx = ix + NB_DX[d];
    const jz = iz + NB_DZ[d];
    if (jx < 0 || jz < 0 || jx >= n || jz >= n) continue;
    if (h[i] - h[jz * n + jx] > DROP_MIN) return true;
  }
  return false;
}

/** March from the ledge-top cell (ix, iz) in each of 8 directions; the first walkable lower cell reached becomes a drop edge. */
function addDropEdges(
  arena: ArenaDef,
  walk: Uint8Array,
  solidOk: Uint8Array,
  h: Float32Array,
  n: number,
  origin: number,
  cell: number,
  ix: number,
  iz: number,
  toList: number[],
  costList: number[],
  kindList: number[],
): void {
  const i = iz * n + ix;
  const x0 = origin + (ix + 0.5) * cell;
  const z0 = origin + (iz + 0.5) * cell;
  const h0 = h[i];
  for (let d = 0; d < 8; d++) {
    const ux = NB_DX[d] / (d < 4 ? 1 : Math.SQRT2);
    const uz = NB_DZ[d] / (d < 4 ? 1 : Math.SQRT2);
    let prevG = h0;
    let dropped = false;
    let found = -1;
    let foundLen = 0;
    for (let s = 0.25; s <= 4.0 + 1e-9; s += 0.25) {
      const x = x0 + ux * s;
      const z = z0 + uz * s;
      const g = arenaGroundHeight(arena, x, z);
      if (g > prevG + ARENA_STEP_UP * 0.99) break; // a cliff in the way
      prevG = g;
      if (g < h0 - DROP_MIN) dropped = true;
      const jx = Math.floor((x - origin) / cell);
      const jz = Math.floor((z - origin) / cell);
      if (jx < 0 || jz < 0 || jx >= n || jz >= n) break;
      const j = jz * n + jx;
      if (j === i) continue;
      if (solidOk[j] === 0) break; // a solid (or the wall) in the way
      if (!dropped) continue;
      const fall = h0 - h[j];
      if (fall > DROP_MAX) break;
      if (walk[j] === 1 && fall > DROP_MIN) {
        found = j;
        foundLen = s;
        break;
      }
    }
    if (found >= 0) {
      toList.push(found);
      costList.push(foundLen + 1.0);
      kindList.push(EDGE_DROP);
    }
  }
}

// ── Cell lookup ───────────────────────────────────────────────────────────────

export function cellOf(g: NavGrid, x: number, z: number): number {
  const ix = Math.floor((x - g.origin) / g.cell);
  const iz = Math.floor((z - g.origin) / g.cell);
  if (ix < 0 || iz < 0 || ix >= g.n || iz >= g.n) return -1;
  return iz * g.n + ix;
}

export function cellX(g: NavGrid, i: number): number {
  return g.origin + ((i % g.n) + 0.5) * g.cell;
}

export function cellZ(g: NavGrid, i: number): number {
  return g.origin + (Math.floor(i / g.n) + 0.5) * g.cell;
}

/** The walkable cell nearest to (x, z) (spiral search up to `maxRing` cells), or -1. Prefers a cell on the same level as `level` when given. */
export function nearestWalkCell(g: NavGrid, x: number, z: number, maxRing = 5, level?: number): number {
  const c = cellOf(g, x, z);
  if (c < 0) {
    // outside the grid: clamp
    const half = g.n * g.cell * 0.5;
    const cx = Math.max(-half + g.cell * 0.5, Math.min(half - g.cell * 0.5, x));
    const cz = Math.max(-half + g.cell * 0.5, Math.min(half - g.cell * 0.5, z));
    return nearestWalkCell(g, cx, cz, maxRing, level);
  }
  const ix0 = c % g.n;
  const iz0 = Math.floor(c / g.n);
  let best = -1;
  let bestD = Infinity;
  for (let r = 0; r <= maxRing; r++) {
    if (best >= 0 && (r - 1) * g.cell > Math.sqrt(bestD)) break;
    for (let dz = -r; dz <= r; dz++) {
      for (let dx = -r; dx <= r; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dz)) !== r) continue;
        const jx = ix0 + dx;
        const jz = iz0 + dz;
        if (jx < 0 || jz < 0 || jx >= g.n || jz >= g.n) continue;
        const j = jz * g.n + jx;
        if (g.walk[j] === 0) continue;
        if (level !== undefined && Math.abs(g.h[j] - level) > 0.5) continue;
        const px = g.origin + (jx + 0.5) * g.cell - x;
        const pz = g.origin + (jz + 0.5) * g.cell - z;
        const d = px * px + pz * pz;
        if (d < bestD) {
          bestD = d;
          best = j;
        }
      }
    }
  }
  return best;
}

// ── Straight-line test ───────────────────────────────────────────────────────

/** Outcomes of {@link lineWalk}. */
export const LINE_BLOCKED = 0;
export const LINE_OK = 1;
export const LINE_DROP = 2;

/**
 * Can a grounded body walk the straight line A -> B on `g`? Samples every 0.3 m:
 *  - the ground may never step UP by more than ARENA_STEP_UP between samples (a cliff);
 *  - a height LOSS over a ledge (> DROP_MIN within 0.6 m) is allowed only with `allowDrop` (result LINE_DROP) and only down to
 *    DROP_MAX in total; samples AFTER the first drop need only be clear of solids (the sim's push-out settles the landing);
 *  - samples before the first drop must be `walk` cells (clear of cliffs and solids) unless `solids` is false (then only the
 *    cliff-clearance part is tested: used to ask "is TERRAIN in the way?", leaving solids to the steering feelers).
 */
export function lineWalk(g: NavGrid, x0: number, z0: number, x1: number, z1: number, allowDrop: boolean, solids = true): number {
  const dx = x1 - x0;
  const dz = z1 - z0;
  const len = Math.sqrt(dx * dx + dz * dz);
  const steps = Math.max(1, Math.ceil(len / 0.3));
  let prevG = arenaGroundHeight(g.arena, x0, z0);
  let top = prevG;
  let dropped = false;
  for (let k = 1; k <= steps; k++) {
    const t = k / steps;
    const x = x0 + dx * t;
    const z = z0 + dz * t;
    const gy = arenaGroundHeight(g.arena, x, z);
    if (gy > prevG + ARENA_STEP_UP * 0.99) return LINE_BLOCKED;
    if (gy < top - DROP_MIN) {
      if (!allowDrop) return LINE_BLOCKED;
      if (top - gy > DROP_MAX) return LINE_BLOCKED;
      dropped = true;
    }
    prevG = gy;
    const c = cellOf(g, x, z);
    if (c < 0) return LINE_BLOCKED;
    if (!dropped) {
      if (solids ? g.walk[c] === 0 : g.cliffOk[c] === 0) return LINE_BLOCKED;
    } else if (solids && g.solidOk[c] === 0) {
      return LINE_BLOCKED;
    }
    if (gy > top) top = gy;
  }
  return dropped ? LINE_DROP : LINE_OK;
}

// ── A* ───────────────────────────────────────────────────────────────────────

// Shared binary heap (lazy deletion). Single-threaded, so one module-level scratch is safe.
let heapKey = new Float32Array(1 << 14);
let heapNode = new Int32Array(1 << 14);
let heapLen = 0;

function heapPush(key: number, node: number): void {
  if (heapLen >= heapKey.length) {
    const nk = new Float32Array(heapKey.length * 2);
    nk.set(heapKey);
    heapKey = nk;
    const nn = new Int32Array(heapNode.length * 2);
    nn.set(heapNode);
    heapNode = nn;
  }
  let i = heapLen++;
  while (i > 0) {
    const p = (i - 1) >> 1;
    if (heapKey[p] <= key) break;
    heapKey[i] = heapKey[p];
    heapNode[i] = heapNode[p];
    i = p;
  }
  heapKey[i] = key;
  heapNode[i] = node;
}

function heapPop(): number {
  const top = heapNode[0];
  heapLen--;
  if (heapLen > 0) {
    const key = heapKey[heapLen];
    const node = heapNode[heapLen];
    let i = 0;
    for (;;) {
      let c = 2 * i + 1;
      if (c >= heapLen) break;
      if (c + 1 < heapLen && heapKey[c + 1] < heapKey[c]) c++;
      if (heapKey[c] >= key) break;
      heapKey[i] = heapKey[c];
      heapNode[i] = heapNode[c];
      i = c;
    }
    heapKey[i] = key;
    heapNode[i] = node;
  }
  return top;
}

/** Per-searcher scratch (one per bot) so A* allocates nothing after construction. */
export class NavSearch {
  private readonly gs: Float32Array;
  private readonly stamp: Int32Array;
  private readonly parent: Int32Array;
  private readonly closed: Int32Array;
  private serial = 0;
  /** The last path found: cell indices start -> goal, `pathLen` of them. */
  path: Int32Array;
  pathLen = 0;
  /** Total cost and metric length of the last path. */
  pathCost = 0;
  pathMetres = 0;
  /** True when the last path crosses a drop edge. */
  hasDrop = false;

  constructor(cells: number) {
    this.gs = new Float32Array(cells);
    this.stamp = new Int32Array(cells);
    this.parent = new Int32Array(cells);
    this.closed = new Int32Array(cells);
    this.path = new Int32Array(512);
  }

  /**
   * A* from cell `s` to cell `goal`. `dropExtra`: added cost (metres) of each drop edge, `Infinity` = never drop.
   * `jumpOk`: jump edges allowed. Returns true and fills {@link path} when reachable.
   */
  find(g: NavGrid, s: number, goal: number, dropExtra: number, jumpOk: boolean): boolean {
    this.pathLen = 0;
    this.hasDrop = false;
    if (s < 0 || goal < 0) return false;
    if (s === goal) {
      this.path[0] = s;
      this.pathLen = 1;
      this.pathCost = 0;
      this.pathMetres = 0;
      return true;
    }
    const n = g.n;
    const gxc = goal % n;
    const gzc = Math.floor(goal / n);
    const cell = g.cell;
    this.serial++;
    const ser = this.serial;
    heapLen = 0;
    this.gs[s] = 0;
    this.stamp[s] = ser;
    this.parent[s] = -1;
    heapPush(0, s);
    let expanded = 0;
    while (heapLen > 0) {
      const u = heapPop();
      if (this.closed[u] === ser) continue;
      this.closed[u] = ser;
      if (u === goal) {
        this.reconstruct(g, s, goal);
        return true;
      }
      expanded++;
      if (expanded > 9000) break;
      const gu = this.gs[u];
      for (let e = g.adjStart[u]; e < g.adjStart[u + 1]; e++) {
        const kind = g.adjKind[e];
        if (kind === EDGE_DROP && dropExtra === Infinity) continue;
        if (kind === EDGE_JUMP && !jumpOk) continue;
        const v = g.adjTo[e];
        const nc = gu + g.adjCost[e] + (kind === EDGE_DROP ? dropExtra : 0);
        if (this.stamp[v] !== ser) {
          this.stamp[v] = ser;
        } else if (nc >= this.gs[v] - 1e-6) {
          continue;
        }
        this.gs[v] = nc;
        this.parent[v] = u;
        const hx = ((v % n) - gxc) * cell;
        const hz = (Math.floor(v / n) - gzc) * cell;
        heapPush(nc + Math.sqrt(hx * hx + hz * hz), v);
      }
    }
    return false;
  }

  private reconstruct(g: NavGrid, s: number, goal: number): void {
    let len = 0;
    for (let c = goal; c >= 0; c = this.parent[c]) {
      len++;
      if (c === s) break;
    }
    if (this.path.length < len) this.path = new Int32Array(len * 2);
    let idx = len - 1;
    let metres = 0;
    let drop = false;
    let prev = -1;
    for (let c = goal; c >= 0; c = this.parent[c]) {
      this.path[idx--] = c;
      if (prev >= 0) {
        const dx = cellX(g, prev) - cellX(g, c);
        const dz = cellZ(g, prev) - cellZ(g, c);
        metres += Math.sqrt(dx * dx + dz * dz);
        if (g.h[c] - g.h[prev] > DROP_MIN) drop = true;
      }
      prev = c;
      if (c === s) break;
    }
    this.pathLen = len;
    this.pathCost = this.gs[goal];
    this.pathMetres = metres;
    this.hasDrop = drop;
  }
}
